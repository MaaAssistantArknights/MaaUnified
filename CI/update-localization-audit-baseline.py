#!/usr/bin/env python3
"""Regenerate the localization resx audit baseline (Tests/Localization/LocalizationResxBaseline.json).

The baseline freezes the drift that predates the dotted-key contract so CI can validate only
new keys: legacy non-conforming names, already-missing translations and already-misordered
entries are recorded here instead of being renamed/reordered in one batch.

Run from the repository root after intentionally adding/removing localization keys:

    python3 CI/update-localization-audit-baseline.py
"""

from __future__ import annotations

import collections
import json
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LOCALIZATION_DIR = REPO_ROOT / "Application" / "Resources" / "Localization"
BASELINE_PATH = REPO_ROOT / "Tests" / "Localization" / "LocalizationResxBaseline.json"

LANGUAGE_FILES = {
    "zh-cn": "UiTexts.resx",
    "zh-tw": "UiTexts.zh-TW.resx",
    "en-us": "UiTexts.en-US.resx",
    "ja-jp": "UiTexts.ja-JP.resx",
    "ko-kr": "UiTexts.ko-KR.resx",
    "pallas": "UiTexts.qps-Ploc.resx",
}
FIVE_LANGUAGES = ("zh-cn", "zh-tw", "en-us", "ja-jp", "ko-kr")
KEY_PATTERN = re.compile(r"^[A-Za-z][A-Za-z0-9]*(\.[A-Za-z0-9]+)+$")


def load_keys(path: Path) -> list[str]:
    return re.findall(r'<data name="([^"]+)"', path.read_text(encoding="utf-8"))


def main() -> None:
    keys_by_language = {
        language: load_keys(LOCALIZATION_DIR / file_name)
        for language, file_name in LANGUAGE_FILES.items()
    }

    non_conforming = sorted(
        {
            key
            for language in FIVE_LANGUAGES
            for key in keys_by_language[language]
            if not KEY_PATTERN.match(key)
        }
    )

    reference = set()
    for language in FIVE_LANGUAGES:
        reference |= set(keys_by_language[language])
    allowed_missing: dict[str, list[str]] = {}
    for language in FIVE_LANGUAGES:
        missing = sorted(reference - set(keys_by_language[language]))
        if missing:
            allowed_missing[language] = missing

    allowed_duplicates: dict[str, list[str]] = {}
    for language, keys in keys_by_language.items():
        counts = collections.Counter(keys)
        duplicates = sorted(key for key, count in counts.items() if count > 1)
        if duplicates:
            allowed_duplicates[language] = duplicates

    allowed_inversions = {}
    for language, keys in keys_by_language.items():
        allowed_inversions[language] = sum(
            1 for previous, current in zip(keys, keys[1:]) if previous > current
        )

    baseline = {
        "_comment": "Generated by CI/update-localization-audit-baseline.py; "
        "records pre-existing drift so CI only validates new keys.",
        "legacyNonConformingKeys": non_conforming,
        "allowedMissingKeys": allowed_missing,
        "allowedDuplicateKeys": allowed_duplicates,
        "allowedInversions": allowed_inversions,
    }

    BASELINE_PATH.parent.mkdir(parents=True, exist_ok=True)
    BASELINE_PATH.write_text(
        json.dumps(baseline, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {BASELINE_PATH} ({len(non_conforming)} legacy keys)")


if __name__ == "__main__":
    main()
